/// Current app language: 'en' (default) or 'ur'.
final ValueNotifier<String> appLang = ValueNotifier<String>('en');

bool get isUrdu => appLang.value == 'ur';

/// Switches language (also switches date/month names).
void applyLanguage(String code) {
  final c = code == 'ur' ? 'ur' : 'en';
  Intl.defaultLocale = c;
  appLang.value = c;
}

/// Translates an English phrase. English text is the key, so a missing
/// Urdu entry simply shows the English text. `{name}` placeholders are
/// replaced from [args].
String tr(String en, [Map<String, Object?>? args]) {
  var s = (appLang.value == 'ur' ? urduStrings[en] : null) ?? en;
  if (args != null) {
    args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  }
  return s;
}

